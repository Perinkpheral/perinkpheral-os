/** Native-grid digits: a narrow zero, a footed one and a flat-topped three.
 * The other digits retain Jersey's drawings. All figures share the existing widest advance.
 * Separate optical masters keep the face's stem weight and open counters at each size.
 */
object JerseyDigits {
    private val faces = mapOf(
        "Jersey10-Regular.ttf" to 18.6667,
        "Jersey15-Regular.ttf" to 27.0,
        "Jersey20-Regular.ttf" to 34.0,
        "Jersey25-Regular.ttf" to 41.0,
    )

    fun matches(fileName: String, pixels: Double): Boolean =
        faces[fileName]?.let { kotlin.math.abs(it - pixels) < 0.0001 } ?: false

    fun glyph(codePoint: Int, original: FontFace.Glyph, reference: FontFace.Glyph): FontFace.Glyph {
        val drawing = drawings[reference.height to codePoint.toChar()]
        val rows = drawing?.trimIndent()?.lines()?.map { row ->
            require(row.all { it == '#' || it == '.' })
            BooleanArray(row.length) { row[it] == '#' }
        } ?: original.rows
        require(rows.size == reference.height && rows.all { it.size == rows[0].size })
        val width = rows[0].size
        val left = reference.left + (reference.width - width) / 2
        return FontFace.Glyph(width, rows.size, left, reference.top, reference.advance, rows)
    }

